CREATE TABLE job_title_reference (
    job_title_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    job_title_code VARCHAR2(50) NOT NULL,
    job_title_name VARCHAR2(120) NOT NULL,
    sort_order NUMBER NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_job_title_reference PRIMARY KEY (job_title_id),
    CONSTRAINT uk_job_title_reference_code UNIQUE (job_title_code)
);

CREATE TABLE employment_status_reference (
    status_code VARCHAR2(20) NOT NULL,
    status_name VARCHAR2(50) NOT NULL,
    sort_order NUMBER NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_employment_status_reference PRIMARY KEY (status_code)
);


CREATE TABLE country (
    country_code CHAR(2) NOT NULL,
    country_name VARCHAR2(100) NOT NULL,
    default_currency_code CHAR(3) NOT NULL,
    CONSTRAINT pk_country PRIMARY KEY (country_code)
);

CREATE TABLE department (
    department_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    department_code VARCHAR2(30) NOT NULL,
    department_name VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_department PRIMARY KEY (department_id),
    CONSTRAINT uk_department_code UNIQUE (department_code)
);

CREATE TABLE employee (
    employee_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_number VARCHAR2(30) NOT NULL,
    first_name VARCHAR2(80) NOT NULL,
    last_name VARCHAR2(80) NOT NULL,
    email VARCHAR2(150) NOT NULL,
    country_code CHAR(2) NOT NULL,
    department_id NUMBER NOT NULL,
    job_title VARCHAR2(120) NOT NULL,
    employment_status VARCHAR2(20) NOT NULL,
    hire_date DATE NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_employee PRIMARY KEY (employee_id),
    CONSTRAINT uk_employee_number UNIQUE (employee_number),
    CONSTRAINT uk_employee_email UNIQUE (email),
    CONSTRAINT fk_employee_country FOREIGN KEY (country_code) REFERENCES country(country_code),
    CONSTRAINT fk_employee_department FOREIGN KEY (department_id) REFERENCES department(department_id),
    CONSTRAINT chk_employee_status CHECK (employment_status IN ('ACTIVE', 'ON_LEAVE', 'INACTIVE'))
);

CREATE TABLE salary_record (
    salary_record_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_id NUMBER NOT NULL,
    salary_amount NUMBER(18,2) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    pay_frequency VARCHAR2(20) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE NULL,
    change_reason VARCHAR2(200) NOT NULL,
    created_by VARCHAR2(100) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_salary_record PRIMARY KEY (salary_record_id),
    CONSTRAINT fk_salary_record_employee FOREIGN KEY (employee_id) REFERENCES employee(employee_id),
    CONSTRAINT chk_salary_amount_positive CHECK (salary_amount > 0),
    CONSTRAINT chk_salary_period CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CONSTRAINT uk_salary_employee_effective_from UNIQUE (employee_id, effective_from)
);

CREATE TABLE salary_audit (
    salary_audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_id NUMBER NOT NULL,
    old_salary_record_id NUMBER NULL,
    new_salary_record_id NUMBER NULL,
    action_type VARCHAR2(30) NOT NULL,
    actor_id VARCHAR2(100) NOT NULL,
    action_at TIMESTAMP(6) NOT NULL,
    reason VARCHAR2(250) NOT NULL,
    CONSTRAINT pk_salary_audit PRIMARY KEY (salary_audit_id),
    CONSTRAINT fk_salary_audit_employee FOREIGN KEY (employee_id) REFERENCES employee(employee_id),
    CONSTRAINT fk_salary_audit_old_record FOREIGN KEY (old_salary_record_id) REFERENCES salary_record(salary_record_id),
    CONSTRAINT fk_salary_audit_new_record FOREIGN KEY (new_salary_record_id) REFERENCES salary_record(salary_record_id),
    CONSTRAINT chk_salary_audit_action_type CHECK (
        action_type IN ('SALARY_CREATED', 'SALARY_CHANGED', 'FUTURE_CHANGE_SCHEDULED', 'FUTURE_CHANGE_REVISED')
    )
);

CREATE INDEX idx_employee_country ON employee(country_code);
CREATE INDEX idx_employee_department ON employee(department_id);
CREATE INDEX idx_employee_status ON employee(employment_status);

CREATE INDEX idx_salary_record_employee_effective_to ON salary_record(employee_id, effective_to);

CREATE INDEX idx_salary_audit_employee ON salary_audit(employee_id);
CREATE INDEX idx_salary_audit_action_at ON salary_audit(action_at);
